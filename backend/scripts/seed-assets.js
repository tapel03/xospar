// Generates db/seeds/assets.sql from the JS catalogue. Run: npm run seed
import { writeFileSync } from 'node:fs';
import { ASSETS } from '../db/seeds/assets.js';

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);
const rows = ASSETS.map((a) =>
  `(${q(a.sym)}, ${q(a.name)}, ${q(a.cat)}, ${a.dec}, ${q(a.quote?.provider)}, ${q(a.quote?.symbol)}, ${q(JSON.stringify(a.candles))}::jsonb)`);
const sql = `-- generated by scripts/seed-assets.js, do not edit by hand
INSERT INTO assets (sym, name, category, decimals, quote_provider, quote_symbol, candle_routes) VALUES
${rows.join(',\n')}
ON CONFLICT (sym) DO UPDATE SET name = EXCLUDED.name, category = EXCLUDED.category, decimals = EXCLUDED.decimals,
  quote_provider = EXCLUDED.quote_provider, quote_symbol = EXCLUDED.quote_symbol, candle_routes = EXCLUDED.candle_routes;
`;
writeFileSync(new URL('../db/seeds/assets.sql', import.meta.url), sql);
console.log(`wrote ${ASSETS.length} assets to db/seeds/assets.sql`);
