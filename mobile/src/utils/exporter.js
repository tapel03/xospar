import { Platform } from 'react-native';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { File, Paths } from 'expo-file-system';

/**
 * doc = { title, subtitle, sections: [{ heading, note?, stats?: [label, value][], headers?: string[], rows?: any[][] }] }
 * The same document becomes either a PDF or a CSV file.
 */

const esc = (v) => String(v == null ? '' : v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const CSS = `
  body { font-family: -apple-system, Helvetica, Arial, sans-serif; color: #1b1f1e; padding: 28px; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  h2 { font-size: 15px; margin: 24px 0 8px; padding-bottom: 4px; border-bottom: 1px solid #d5dad8; }
  .sub, .note, .foot { color: #6b7472; font-size: 11px; margin: 2px 0 8px; }
  .foot { margin-top: 28px; }
  table { width: 100%; border-collapse: collapse; font-size: 11px; margin-bottom: 8px; }
  th { text-align: left; background: #eef1f0; padding: 6px 8px; border-bottom: 1px solid #d5dad8; }
  td { padding: 5px 8px; border-bottom: 1px solid #eceeed; }
  table.stats td:first-child { color: #6b7472; width: 55%; }
  .r { text-align: right; font-weight: 600; }
`;

export function buildHtml(doc) {
  const body = doc.sections.map((s) => {
    const stats = s.stats ? `<table class="stats">${s.stats.map(([k, v]) => `<tr><td>${esc(k)}</td><td class="r">${esc(v)}</td></tr>`).join('')}</table>` : '';
    const table = s.headers
      ? `<table><thead><tr>${s.headers.map((h) => `<th>${esc(h)}</th>`).join('')}</tr></thead><tbody>${s.rows.map((r) => `<tr>${r.map((x) => `<td>${esc(x)}</td>`).join('')}</tr>`).join('')}</tbody></table>`
      : '';
    return `<h2>${esc(s.heading)}</h2>${s.note ? `<p class="note">${esc(s.note)}</p>` : ''}${stats}${table}`;
  }).join('');
  return `<html><head><meta charset="utf-8" /><meta name="viewport" content="width=device-width, initial-scale=1" /><style>${CSS}</style></head><body><h1>${esc(doc.title)}</h1><p class="sub">${esc(doc.subtitle)}</p>${body}<p class="foot">Generated by Edgeline. Values in this prototype are simulated. Not financial advice.</p></body></html>`;
}

const cell = (v) => {
  const s = String(v == null ? '' : v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

export function buildCsv(doc) {
  const out = [cell(doc.title), cell(doc.subtitle), ''];
  doc.sections.forEach((s) => {
    out.push(cell(s.heading));
    if (s.stats) s.stats.forEach(([k, v]) => out.push([k, v].map(cell).join(',')));
    if (s.headers) {
      out.push(s.headers.map(cell).join(','));
      s.rows.forEach((r) => out.push(r.map(cell).join(',')));
    }
    out.push('');
  });
  return out.join('\n');
}

async function share(uri, mimeType, UTI, name) {
  if (!(await Sharing.isAvailableAsync())) throw new Error('Sharing is not available on this device.');
  await Sharing.shareAsync(uri, { mimeType, UTI, dialogTitle: `Export ${name}` });
}

export async function exportPdf(doc, name) {
  const html = buildHtml(doc);
  if (Platform.OS === 'web') { await Print.printAsync({ html }); return; }
  const { uri } = await Print.printToFileAsync({ html });
  await share(uri, 'application/pdf', 'com.adobe.pdf', name);
}

export async function exportCsv(doc, name) {
  const text = `\uFEFF${buildCsv(doc)}`; // BOM so Excel reads the file as UTF-8
  if (Platform.OS === 'web') {
    const blob = new Blob([text], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url; a.download = `${name}.csv`; a.click();
    URL.revokeObjectURL(url);
    return;
  }
  const file = new File(Paths.cache, `${name}.csv`);
  file.create({ overwrite: true });
  file.write(text);
  await share(file.uri, 'text/csv', 'public.comma-separated-values-text', name);
}